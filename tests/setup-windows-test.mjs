// Windows lifecycle acceptance for Helm setup. Never uses real user MCP config or CLIs.
import assert from 'node:assert/strict';
import {mkdtempSync,mkdirSync,writeFileSync,readFileSync,existsSync,rmSync,cpSync,readdirSync} from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
if (process.platform !== 'win32') throw Error('Windows-only test invoked on a non-Windows platform');
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const tmp=mkdtempSync(path.join(os.tmpdir(),'helm-win-setup-'));
const home=path.join(tmp,'sandbox-home');
const cleanPath=[path.dirname(process.execPath),path.join(process.env.SystemRoot||'C:\\Windows','System32')].join(path.delimiter);
const env={...process.env,USERPROFILE:home,HOME:home,APPDATA:path.join(home,'AppData','Roaming'),LOCALAPPDATA:path.join(home,'AppData','Local'),PATH:cleanPath};
for(const dir of [home,env.APPDATA,env.LOCALAPPDATA])mkdirSync(dir,{recursive:true});
const target=path.join(home,'.helm','plugin');
const state=path.join(home,'.helm','install.json');
const shim=path.join(home,'.helm','bin','helm.cmd');
const output=(r)=>(r.stdout||'')+(r.stderr||'');
const run=(dir,args)=>spawnSync(process.execPath,[path.join(dir,'setup.mjs'),...args],{cwd:tmp,env,encoding:'utf8',timeout:20000});
const check=(r,description)=>assert.equal(r.status,0,description+': '+output(r));
const copy=(where)=>{cpSync(root,where,{recursive:true,filter:f=>!/(^|[\\/])(node_modules|\.git|dist)([\\/]|$)/.test(f)});return where;};
let count=0;const pass=(name)=>{count++;console.log('  PASS '+name);};
try{
  const noCli=(command)=>spawnSync('where.exe',[command],{env,encoding:'utf8'});
  assert.notEqual(noCli('claude').status,0,'test must not reach real Claude CLI');
  assert.notEqual(noCli('codex').status,0,'test must not reach real Codex CLI');
  pass('isolated sandbox cannot reach real MCP clients');
  const first=copy(path.join(tmp,'first'));
  check(run(first,['status']),'status without install');
  assert.ok(!existsSync(state));pass('status is read-only before install');
  check(run(first,['install','--host','codex','--dry-run']),'install dry-run');
  assert.ok(!existsSync(state));pass('install dry-run writes nothing');
  check(run(first,['install','--host','codex']),'install');
  assert.ok(existsSync(target)&&existsSync(state)&&existsSync(shim));pass('install creates isolated managed copy, state and Windows launcher');
  assert.equal(JSON.parse(readFileSync(state,'utf8')).host,'codex');
  assert.match(readFileSync(shim,'utf8'),/HELM-MANAGED-LAUNCHER/);
  assert.equal(JSON.parse(readFileSync(path.join(target,'package.json'),'utf8')).version,'0.8.0');
  const launcher=spawnSync(shim,['version'],{shell:true,env,cwd:tmp,encoding:'utf8',timeout:12000});
  check(launcher,'launcher');
  assert.match(output(launcher),/Helm 0\.8\.0/);pass('Windows launcher executes installed Helm v0.8.0');
  check(run(first,['install','--host','codex','--force']),'repeat install');
  assert.equal(JSON.parse(readFileSync(state,'utf8')).version,'0.8.0');pass('forced install cannot overwrite an existing managed installation');
  check(run(first,['status']),'status with install');pass('status works with missing host executables');
  const second=copy(path.join(tmp,'next-release'));
  let pkg=JSON.parse(readFileSync(path.join(second,'package.json'),'utf8'));pkg.version='0.9.0';
  writeFileSync(path.join(second,'package.json'),JSON.stringify(pkg,null,2));
  const server=path.join(second,'server','mcp.mjs');
  let mcp=readFileSync(server,'utf8');assert.ok(mcp.includes("const VERSION = '0.8.0';"));
  writeFileSync(server,mcp.replace("const VERSION = '0.8.0';","const VERSION = '0.9.0';"));
  writeFileSync(path.join(second,'NEW_MARKER.txt'),'new source marker');
  check(run(second,['update','--dry-run']),'update dry-run');
  assert.equal(JSON.parse(readFileSync(path.join(target,'package.json'),'utf8')).version,'0.8.0');pass('update dry-run changes no installed files');
  check(run(second,['update']),'update');
  assert.equal(JSON.parse(readFileSync(path.join(target,'package.json'),'utf8')).version,'0.9.0');
  assert.ok(existsSync(path.join(target,'NEW_MARKER.txt')));
  const backups=readdirSync(path.join(home,'.helm')).filter(x=>x.startsWith('plugin-backup-'));
  assert.ok(backups.length>=1);pass('update upgrades with verified MCP start and keeps backups');
  let older=run(first,['update']);assert.notEqual(older.status,0);pass('downgrade is refused');
  let protectedDir=path.join(tmp,'unrelated-user-project');mkdirSync(protectedDir);
  writeFileSync(path.join(protectedDir,'precious.txt'),'do not delete');
  const record=JSON.parse(readFileSync(state,'utf8'));writeFileSync(state,JSON.stringify({...record,dir:protectedDir}));
  let un=run(first,['uninstall','--yes']);check(un,'tampered uninstaller');
  assert.ok(existsSync(path.join(protectedDir,'precious.txt')));
  assert.ok(existsSync(target));pass('tampered install record cannot delete a non-Helm directory');
  writeFileSync(state,JSON.stringify(record));
  const kept=path.join(home,'.helm','my-notes.txt');writeFileSync(kept,'keep this');
  check(run(first,['uninstall','--yes','--purge']),'uninstall with purge');
  assert.ok(!existsSync(target)&&!existsSync(shim)&&!existsSync(state));
  assert.equal(readFileSync(kept,'utf8'),'keep this');
  assert.equal(readdirSync(path.join(home,'.helm')).filter(x=>x.startsWith('plugin-backup-')).length,0);
  pass('uninstall purges only owned files/backups, preserves unrelated home files');
  const custom=path.join(tmp,'custom-install');
  check(run(first,['install','--host','codex','--dir',custom]),'custom install');
  assert.ok(existsSync(path.join(custom,'setup.mjs')));
  check(run(first,['uninstall','--yes']),'custom uninstall');
  assert.ok(existsSync(path.join(custom,'setup.mjs')));
  pass('uninstall leaves custom installation path untouched');
  const inPlace=copy(path.join(tmp,'in-place'));
  check(run(inPlace,['install','--host','codex','--in-place']),'in-place install');
  check(run(inPlace,['uninstall','--yes']),'in-place uninstall');
  assert.ok(existsSync(path.join(inPlace,'setup.mjs')));pass('uninstall never deletes in-place source');
  const unrelated=path.join(home,'.helm','plugin');
  mkdirSync(unrelated,{recursive:true});
  writeFileSync(path.join(unrelated,'user.txt'),'personal data');
  let refusal=run(first,['install','--host','codex']);assert.notEqual(refusal.status,0);
  assert.ok(existsSync(path.join(unrelated,'user.txt')));pass('installer refuses to overwrite unrecorded files');
  console.log(count+'/'+count+' Windows setup lifecycle checks passed');
}finally{rmSync(tmp,{recursive:true,force:true});}
