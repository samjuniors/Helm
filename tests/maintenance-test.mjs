#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {ensureShellPath,removeShellPath,modifyShellProfile} from '../server/posix-path.mjs';
import {registerProjectCodex,unregisterProjectCodex,projectCodexStatus} from '../server/project-mcp.mjs';
import {createReleaseZip,crc32} from '../scripts/zip-release.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'helm-maintenance-'));
let total=0;const pass=(msg)=>{total++;console.log('  PASS '+msg);};
try {
  const home=path.join(temp,'home');fs.mkdirSync(home);
  const user=path.join(home,'.profile');fs.writeFileSync(user,'# custom PATH stays\n');
  const first=ensureShellPath({home,shell:'/bin/bash'});assert.ok(first.files.includes(user));
  assert.match(fs.readFileSync(user,'utf8'),/HELM MANAGED PATH/);
  assert.match(fs.readFileSync(user,'utf8'),/custom PATH stays/);pass('POSIX user PATH added without replacing custom profile content');
  assert.equal(ensureShellPath({home,shell:'/bin/bash'}).changed.length,0);pass('POSIX PATH repair is idempotent');
  removeShellPath(first.files,{home});assert.doesNotMatch(fs.readFileSync(user,'utf8'),/HELM MANAGED PATH/);
  assert.match(fs.readFileSync(user,'utf8'),/custom PATH stays/);pass('uninstall removes only Helm-owned PATH block');
  const foreign=path.join(home,'.zprofile');fs.writeFileSync(foreign,'# manually edited\nexport PATH="$HOME/tools:$PATH"\n');
  assert.equal(modifyShellProfile(foreign,'remove').changed,false);pass('unowned profiles are never removed');
  const linked=path.join(home,'.linked');fs.symlinkSync(foreign,linked);assert.throws(()=>modifyShellProfile(linked,'add'),/symlink/);pass('symlink shell profiles cannot be modified');
  const project=path.join(temp,'project');fs.mkdirSync(project);
  const config=path.join(project,'.codex','config.toml');fs.mkdirSync(path.dirname(config));
  fs.writeFileSync(config,'model = "keep"\n');
  const server=path.join(root,'server','mcp.mjs');
  assert.equal(registerProjectCodex(project,server,process.execPath,'helm',{dryRun:true}).status,'would-register');
  assert.equal(fs.readFileSync(config,'utf8'),'model = "keep"\n');pass('project Codex preview never changes existing config');
  registerProjectCodex(project,server,process.execPath);
  assert.equal(projectCodexStatus(project).status,'managed');
  assert.match(fs.readFileSync(config,'utf8'),/model = "keep"/);
  assert.equal(registerProjectCodex(project,server,process.execPath).status,'already-managed');pass('project Codex config is owned and idempotent');
  unregisterProjectCodex(project);assert.equal(projectCodexStatus(project).status,'absent');
  assert.match(fs.readFileSync(config,'utf8'),/model = "keep"/);pass('project uninstall removes only managed Codex section');
  fs.writeFileSync(config,'[mcp_servers.helm]\ncommand = "custom"\n');
  assert.throws(()=>registerProjectCodex(project,server),/will not overwrite/);
  assert.throws(()=>unregisterProjectCodex(project),/not Helm-managed/);pass('foreign project MCP configuration cannot be overwritten or removed');
  const payload=path.join(temp,'payload');fs.mkdirSync(payload);fs.writeFileSync(path.join(payload,'.hidden'),'secret-but-packaged');
  fs.writeFileSync(path.join(payload,'readme.txt'),'hello');
  const output=path.join(temp,'test.zip');createReleaseZip(payload,['.hidden','readme.txt'],output);
  const bytes=fs.readFileSync(output);assert.equal(bytes.readUInt32LE(0),0x04034b50);
  assert.ok(bytes.includes(Buffer.from('helm/.hidden')));assert.ok(bytes.includes(Buffer.from('helm/readme.txt')));
  assert.equal(bytes.readUInt32LE(bytes.length-22),0x06054b50);
  assert.equal(crc32(Buffer.from('123456789')),0xcbf43926);pass('portable ZIP includes dotfiles, valid framing and CRC32');
  assert.throws(()=>createReleaseZip(payload,['../escape'],output),/unsafe package entry/);pass('ZIP rejects path traversal');
  const bad=spawnSync(process.execPath,[path.join(root,'scripts','manual-release.mjs'),'--unknown'],{cwd:root,encoding:'utf8'});
  assert.notEqual(bad.status,0);assert.match(bad.stderr,/Usage: helm release/);pass('manual release rejects unrecognized flags without writing');
  const repair=spawnSync(process.execPath,[path.join(root,'server','repair.mjs'),'--dry-run'],{cwd:root,env:{...process.env,HOME:home,USERPROFILE:home},encoding:'utf8'});
  assert.notEqual(repair.status,0);assert.match(repair.stderr,/no managed installation record/);pass('repair refuses missing installation state without writing');
  console.log(total+'/'+total+' maintenance safety checks passed');
} finally{fs.rmSync(temp,{recursive:true,force:true});}
